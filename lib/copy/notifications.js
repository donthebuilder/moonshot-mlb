/** Delay / suspension / postponement headline from the league's own words. */
export function gameOffHeadline(kind, reasonRaw) {
  const m = txt(reasonRaw).match(/(?:[:(]\s*)([A-Za-z][A-Za-z ]*?)\)?\s*$/)
  let reason = m ? m[1].trim() : ''
  if (/^(start|game)$/i.test(reason)) reason = ''
  const cap = reason ? reason.charAt(0).toUpperCase() + reason.slice(1).toLowerCase() : ''
  if (kind === 'postponed') return `Postponed${cap ? ` (${cap.toLowerCase()})` : ''}`
  if (kind === 'suspended') return `Suspended${cap ? ` (${cap.toLowerCase()})` : ''}`
  return cap ? `${cap} delay` : 'Delay'
}

