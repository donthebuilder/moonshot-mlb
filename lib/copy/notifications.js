// ── small shared words ──────────────────────────────────────────────────────
const num = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0)
const txt = (v) => String(v == null ? '' : v).trim()
const ord = (k) => `${k}${[11, 12, 13].includes(k % 100) ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' }[k % 10] || 'th')}`
const cp = (s) => [...String(s)].length          // length in characters, emoji counted once
const SEP = ' · '

export const EMOJI = { mlb: '⚾', nfl: '\u{1F3C8}', nhl: '\u{1F6A8}', nba: '\u{1F3C0}' }
export const LIMITS = { title: 26, body: 48, keyBy: 30 }

/** "1 pick" / "2 picks" / "0 picks". Pass `many` for an irregular plural. */
export const plural = (n, one, many) => `${n} ${n === 1 ? one : (many || `${one}s`)}`
/** "is" / "are" for a count. */
export const isAre = (n) => (n === 1 ? 'is' : 'are')

/** "A", "A and B", "A, B and C", "A, B +2" -- names are never repeated. */
export function joinNames(names, max = 3) {
  const u = [...new Set((names || []).map(txt).filter(Boolean))]
  if (u.length <= 1) return u[0] || ''
  const shown = u.slice(0, max)
  const more = u.length - shown.length
  if (more > 0) return `${shown.join(', ')} +${more}`
  return `${shown.slice(0, -1).join(', ')} and ${shown[shown.length - 1]}`
}

/** Last name ("Jr." / "III" dropped): the form a 26-character title falls back to. */
export function lastNameOf(full) {
  const parts = txt(full).split(/\s+/).filter(Boolean)
  if (!parts.length) return 'Your guy'
  if (parts.length === 1) return parts[0]
  const tail = parts.slice(1).filter((p) => !/^(jr\.?|sr\.?|i{2,3}|iv|v)$/i.test(p))
  return (tail.length ? tail : parts.slice(1)).join(' ')
}

const clip = (s, n) => (cp(s) <= n ? s : `${[...s].slice(0, n - 1).join('').trimEnd()}…`)

/** "⚾ Full Name suffix" if it fits in the title limit, else with the last name. */
export function titleWith(emoji, name, suffix = '', max = LIMITS.title) {
  const pre = emoji ? `${emoji} ` : ''
  const tail = suffix ? ` ${suffix}` : ''
  const full = `${pre}${name}${tail}`
  if (cp(full) <= max) return full
  return clip(`${pre}${lastNameOf(name)}${tail}`, max)
}
/** A title with no name in it. */
export const titleOnly = (emoji, words, max = LIMITS.title) => clip(`${emoji ? `${emoji} ` : ''}${words}`, max)

/** One line of facts: parts joined with " · ", trailing parts dropped (never clipped mid-fact) until it fits. */
export function fitBody(parts, max = LIMITS.body) {
  const p = parts.map(txt).filter(Boolean)
  while (p.length > 1 && cp(p.join(SEP)) > max) p.pop()
  return clip(p.join(SEP), max)
}

/** Scoreboard shorthand: ▲6 = top of the 6th, ▼7 = bottom of the 7th. */
export function inningShort(half, inning) {
  const n = num(inning)
  if (!n) return ''
  return `${/^top|^middle/i.test(txt(half)) ? '▲' : '▼'}${n}`
}
/** The long form, where there is room (Discord, on-page toasts): "Top 7th" / "Bottom 7th". */
export function inningText(half, inning) {
  const n = num(inning)
  if (!n) return ''
  return `${/^top|^middle/i.test(txt(half)) ? 'Top' : 'Bottom'} ${ord(n)}`
}

/** "NYY 3, TB 2": LEADER FIRST, everywhere. "Tied 3-3". '' when either side is unknown. */
export function scoreText({ away, home, awayScore, homeScore } = {}) {
  const a = txt(away); const h = txt(home)
  if (!a || !h || awayScore == null || homeScore == null) return ''
  const as = num(awayScore); const hs = num(homeScore)
  if (as === hs) return `Tied ${as}-${hs}`
  return as > hs ? `${a} ${as}, ${h} ${hs}` : `${h} ${hs}, ${a} ${as}`
}
/** "▼7" + "NYY 3, TB 2" as two parts, in glance order. */
export const gameParts = (g) => [inningShort(g?.half, g?.inning), scoreText(g)].filter(Boolean)

/** "7:05 PM ET" from epoch ms. */
export function timeET(ms) {
  try {
    const s = new Intl.DateTimeFormat('en-US', { timeZone: 'America/New_York', hour: 'numeric', minute: '2-digit' }).format(new Date(ms))
    return `${s} ET`
  } catch { return '' }
}

