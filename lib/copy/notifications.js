// set), in the same words: name once, the situation in the body, the time or the
// score in the first 30 characters. Starters (a goalie confirmed or changed, an NBA
// five) ride the one new category `starter`; a man who is out is `scratched`; a
// delay, postponement or moved start is `gameoff` -- the MLB keys, not new ones.

/** "7:05 PM ET", or "Sun 1:00 PM ET" when the game is not today (Eastern). */
export function whenET(ms, now = Date.now()) {
  const t = timeET(ms)
  if (!t) return ''
  try {
    const f = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit' })
    if (f.format(new Date(ms)) === f.format(new Date(now))) return t
    const d = new Intl.DateTimeFormat('en-US', { timeZone: 'America/New_York', weekday: 'short' }).format(new Date(ms))
    return `${d} ${t}`
  } catch { return t }
}

const START_WORD = { nfl: 'Kickoff', nhl: 'Puck drop', nba: 'Tip' }
/** "Rain delay" from the league's own words ("Delayed", "Rain Delay", "Delayed: LIGHTNING"). */
export function delayHeadline(detail) {
  const m = txt(detail).match(/\b(rain|weather|lightning|snow|fog|power|wind|fire|security)\b/i)
  return m ? `${m[1].charAt(0).toUpperCase()}${m[1].slice(1).toLowerCase()} delay` : 'Delay'
}
/**
 * A game with your players is off, late or moved. `kind`: delayed | suspended | postponed | moved | late.
 * Before the start it names the clubs; in a game it carries the period and the score instead.
 */
function gameOffFor(sport, { kind, detail, away, home, count, whenMs, now, parts = [] }) {
  const start = START_WORD[sport] || 'Start'
  const head = kind === 'moved' ? `${start} moved`
    : kind === 'late' ? `${start} delayed`
      : kind === 'postponed' ? 'Postponed'
        : kind === 'suspended' ? 'Suspended'
          : delayHeadline(detail)
  const who = count > 0 ? `${count} of your players` : ''
  const body = kind === 'moved'
    ? fitBody([`${away} at ${home}`, `now ${whenET(whenMs, now)}`])
    : parts.length ? fitBody([...parts, who]) : fitBody([`${away} at ${home}`, who])
  return { title: titleOnly('⚠️', head), body, short: `${away}-${home}`, group: 'games are off' }
}

