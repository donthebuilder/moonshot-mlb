#!/usr/bin/env node
// THE NOTIFICATION MAP (2026-10-31): every Discord kind the routing table knows, where it goes, who sees it, and what MEMBERS_BOX_ON / LIVE_BOX_ON change.
// Generated from lib/dash/routing.js, never hand-edited:   node --import ./scripts/_esm-resolve.mjs scripts/build-notification-map.mjs          (writes docs/MEMBERS-NOTIFICATIONS.md)
//                                                           node --import ./scripts/_esm-resolve.mjs scripts/build-notification-map.mjs --check  (fails when the file is stale: a push gate)
import fs from 'node:fs'
import { ROUTES, PREFIX_ROUTES, routeOf } from '../lib/dash/routing.js'
const OUT = new URL('../docs/MEMBERS-NOTIFICATIONS.md', import.meta.url)
const KINDS = [...Object.keys(ROUTES), ...PREFIX_ROUTES.map(([p]) => `${p}*`)]
const sample = (k) => (k.endsWith('*') ? k.slice(0, -1) + 'x' : k)
const rooms = (env) => {
  const keep = { MEMBERS_BOX_ON: process.env.MEMBERS_BOX_ON, LIVE_BOX_ON: process.env.LIVE_BOX_ON }
  Object.assign(process.env, env)
  const out = Object.fromEntries(KINDS.map((k) => { const r = routeOf(sample(k)); return [k, r ? r.rooms.join(' + ') : '(none)'] }))
  for (const [k, v] of Object.entries(keep)) { if (v === undefined) delete process.env[k]; else process.env[k] = v }
  return out
}
const now = rooms({ MEMBERS_BOX_ON: '', LIVE_BOX_ON: '' })
const box = rooms({ MEMBERS_BOX_ON: 'on', LIVE_BOX_ON: 'on' })
const lines = ['# Notification map', '', 'Generated by `scripts/build-notification-map.mjs` from `lib/dash/routing.js`. Do not edit by hand; rerun the script. `--check` fails when this file is stale.', '',
  'Rooms: `members` = #members (paying), `sport` = the product\'s own room, `network` = #dash-network, `partner` = partner servers, `feed`/`receipts`/`donovan` = the named rooms, `x` = X only, `off` = not delivered (the row is still stored).', '',
  '"With boxes on" = `MEMBERS_BOX_ON` and `LIVE_BOX_ON` both on (members box + live box).', '', '| Kind | Who | When | Rooms now | Rooms with boxes on |', '|---|---|---|---|---|']
for (const k of KINDS) {
  const r = k.endsWith('*') ? PREFIX_ROUTES.find(([p]) => `${p}*` === k)[1] : ROUTES[k]
  const esc = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
  lines.push(`| \`${k}\` | ${r?.who || ''} | ${esc(r?.when)} | ${now[k]} | ${box[k] === now[k] ? 'same' : box[k]} |`)
}
const text = `${lines.join('\n')}\n`
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (have !== text) { console.log('FAIL docs/MEMBERS-NOTIFICATIONS.md is stale: run scripts/build-notification-map.mjs'); process.exit(1) }
  console.log(`ok   notification map is current (${KINDS.length} kinds)`)
} else { fs.mkdirSync(new URL('../docs/', import.meta.url), { recursive: true }); fs.writeFileSync(OUT, text); console.log(`wrote docs/MEMBERS-NOTIFICATIONS.md (${KINDS.length} kinds)`) }
